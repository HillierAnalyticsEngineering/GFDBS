"""Code-only checks on a generated function. They run at build time and again whenever evidence changes."""
from __future__ import annotations

import ast
import importlib.util
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ALLOWED_IMPORTS = {"math", "typing", "bisect", "__future__", "toolbox"}
REQUIRED_NAMES = {"evaluate", "check", "PARAMETERS"}
TOOLBOX = Path(__file__).resolve().parent / "toolbox.py"


def structure_errors(module_code: str) -> list[str]:
    """Read the code without running it. Check the shape and the imports."""
    try:
        tree = ast.parse(module_code)
    except SyntaxError as exc:
        return [f"module does not parse: {exc}"]
    names, errors = set(), []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    for node in ast.walk(tree):
        mods = ([a.name for a in node.names] if isinstance(node, ast.Import)
                else [node.module or ""] if isinstance(node, ast.ImportFrom) else [])
        errors += [f"import of '{m}' is not allowed. Use the standard library or toolbox: {sorted(ALLOWED_IMPORTS)}"
                   for m in mods if m.split(".")[0] not in ALLOWED_IMPORTS]
    missing = REQUIRED_NAMES - names
    if missing:
        errors.append(f"module must define {sorted(missing)}")
    return errors


def acceptance_test_code(function_id: str, rule_id: str, measures: list, cases: list) -> str:
    """Turn worked cases into a pytest module. The agent that wrote the function never sees this file."""
    return f'''"""Acceptance tests for {function_id}, generated by the harness from worked cases."""
import json
import pytest
import solution

MEASURES = json.loads({json.dumps(json.dumps(measures))})
CASES = json.loads({json.dumps(json.dumps(cases))})


@pytest.mark.parametrize("case", CASES, ids=[f"case_{{i + 1}}_{{c.get('source', 'library')}}" for i, c in enumerate(CASES)])
def test_worked_case(case):
    if case.get("raises"):
        with pytest.raises(ValueError):
            solution.evaluate(case["inputs"], MEASURES)
        return
    got = solution.evaluate(case["inputs"], MEASURES)
    for key, want in case["expect"].items():
        assert key in got, f"output is missing '{{key}}'"
        if isinstance(want, bool):
            assert got[key] is want, f"{{key}}: expected {{want}}, got {{got[key]}}"
        else:
            assert got[key] == pytest.approx(want, abs=0.01), f"{{key}}: expected {{want}}, got {{got[key]}}"
    findings = solution.check(case["inputs"], MEASURES)
    assert bool(findings) is (not case["expect"].get("passes", True)), "check() must return a finding exactly when the design fails"
    for f in findings:
        assert {{"rule", "severity", "domains", "message", "evidence"}} <= set(f), "finding is missing a field"
        assert f["rule"] == {rule_id!r}


def test_parameters_describe_every_case_input():
    assert isinstance(solution.PARAMETERS, dict) and solution.PARAMETERS
    for case in CASES:
        for name in case["inputs"]:
            assert name in solution.PARAMETERS, f"PARAMETERS must describe '{{name}}'"
'''


def _pytest(folder: Path, file: str) -> dict:
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "--no-header", "-p", "no:cacheprovider",
                           "-c", str(folder / "pytest.ini"), file],
                          capture_output=True, text=True, timeout=120, cwd=folder)
    count = lambda word: int((re.search(rf"(\d+) {word}", proc.stdout) or [0, 0])[1])
    return {"ok": proc.returncode == 0, "passed": count("passed"), "failed": count("failed") + count("error"),
            "output": proc.stdout[-6000:]}


def load_module(folder: Path, tag: str = "solution"):
    """Import a generated function from its folder."""
    spec = importlib.util.spec_from_file_location(f"fn_{tag}", folder / "solution.py")
    module = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(folder))                     # so `from toolbox import ...` resolves
    try:
        spec.loader.exec_module(module)
    finally:
        sys.path.remove(str(folder))
    return module


def conformance_errors(folder: Path, contract: dict, declared_terms: list[dict], measures: list, cases: list) -> list[str]:
    """Does the function honor the interface spec the systems engineer agent wrote?"""
    module, errors = load_module(folder), []
    params = set(module.PARAMETERS)
    needed = [t["name"] for t in contract["inputs"] if not t.get("optional")]
    missing = [n for n in needed if n not in params]
    if missing:
        errors.append(f"The interface spec requires inputs {missing}. PARAMETERS does not describe them.")
    known = {t["name"] for t in contract["inputs"]} | {t["name"] for t in declared_terms}
    stray = sorted(params - known)
    if stray:
        errors.append(f"PARAMETERS has names that are in neither the interface spec nor your terms list: {stray}")
    good = next((c for c in cases if not c.get("raises")), None)
    if good:
        try:
            got = module.evaluate(good["inputs"], measures)
            absent = [t["name"] for t in contract["outputs"] if t["name"] not in got]
            if absent:
                errors.append(f"The interface spec requires outputs {absent}. evaluate() does not return them.")
        except Exception as exc:
            errors.append(f"evaluate() failed on a worked case: {exc}")
    return errors


def run_gates(folder: Path, function_id: str, rule_id: str, module_code: str, test_code: str,
              measures: list, cases: list, contract: dict | None = None, declared_terms: list | None = None) -> dict:
    """All code gates in order. Returns a report whose `errors` list is empty when everything passes."""
    report = {"structure": {"ok": True, "errors": []}, "own_tests": None, "acceptance": None,
              "conformance": {"ok": True, "errors": []}, "errors": []}
    errors = structure_errors(module_code)
    if errors:
        report["structure"] = {"ok": False, "errors": errors}
        report["errors"] = errors
        return report
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "solution.py").write_text(module_code, encoding="utf-8")
    (folder / "test_solution.py").write_text(test_code, encoding="utf-8")
    (folder / "test_acceptance.py").write_text(acceptance_test_code(function_id, rule_id, measures, cases), encoding="utf-8")
    (folder / "pytest.ini").write_text("[pytest]\n", encoding="utf-8")
    shutil.copy(TOOLBOX, folder / "toolbox.py")
    for key, label, file in (("own_tests", "the agent's own tests", "test_solution.py"),
                             ("acceptance", "acceptance tests from worked cases", "test_acceptance.py")):
        report[key] = {**_pytest(folder, file), "label": label}
        if not report[key]["ok"]:
            advice = ("A test you wrote disagrees with the function you wrote, so one of them is wrong. Work that test's inputs "
                      "through the method by hand, state the arithmetic in design_notes, and then correct the function or the "
                      "expectation. Resubmitting the same test and the same function fails the same way."
                      if key == "own_tests" else
                      "These tests come from the worked cases and cannot be changed. Make the function reproduce them exactly: "
                      "the input names, the output names, and the numbers.")
            report["errors"] = [f"{label} failed:\n{report[key]['output'][-1500:]}\n{advice}"]
            return report
    if contract:
        errors = conformance_errors(folder, contract, declared_terms or [], measures, cases)
        report["conformance"] = {"ok": not errors, "errors": errors}
        report["errors"] = errors
    return report


def summary(report: dict) -> dict:
    keep = lambda r: None if r is None else {k: r[k] for k in ("ok", "passed", "failed")}
    return {"structure": report["structure"]["ok"], "own_tests": keep(report["own_tests"]),
            "acceptance": keep(report["acceptance"]), "conformance": report["conformance"]["ok"],
            "ok": not report["errors"]}
